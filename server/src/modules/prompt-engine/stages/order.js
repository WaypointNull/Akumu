function classifyTag(tag) {
  if (!tag) {
    return 'other';
  }
  const normalized = String(tag).toLowerCase();
  if (QUALITY_TAGS.has(normalized)) {
    return 'quality';
  }
  if (COUNT_RE.test(normalized) || COUNT_TAGS.has(normalized)) {
    return 'count';
  }
  if (normalized.includes('(') || FRANCHISE_TAGS.has(normalized)) {
    return 'character';
  }

  // Exact compound phrases (e.g. "depth_of_field", "cozy_reading_nook", "holding_fishing_rod") are more
  // specific than any of their parts, so a whole-tag match overrides the token votes below.
  let exact = 'other';
  let exactWeight = CATEGORY_WEIGHT.other;
  const considerExact = (category) => {
    const weight = CATEGORY_WEIGHT[category];
    if (weight < exactWeight) {
      exact = category;
      exactWeight = weight;
    }
  };
  if (APPEARANCE.has(normalized)) {
    considerExact('appearance');
  }
  if (ENVIRONMENT.has(normalized)) {
    considerExact('environment');
  }
  if (CLOTHING.has(normalized)) {
    considerExact('clothing');
  }
  if (POSE.has(normalized)) {
    considerExact('pose');
  }
  if (EXPRESSION.has(normalized)) {
    considerExact('expression');
  }
  if (COMPOSITION.has(normalized)) {
    considerExact('composition');
  }
  if (exact !== 'other') {
    return exact;
  }

  let best = 'other';
  let bestWeight = CATEGORY_WEIGHT.other;
  const consider = (category) => {
    const weight = CATEGORY_WEIGHT[category];
    if (weight < bestWeight) {
      best = category;
      bestWeight = weight;
    }
  };

  const tokens = normalized.split(/[_-]+/);
  for (const token of tokens) {
    if (QUALITY_TOKEN.has(token)) {
      consider('quality');
    }
    if (GENDER_TOKENS.has(token)) {
      consider('count');
    }
    if (APPEARANCE.has(token)) {
      consider('appearance');
    }
    if (ENVIRONMENT.has(token)) {
      consider('environment');
    }
    if (CLOTHING.has(token)) {
      consider('clothing');
    }
    if (POSE.has(token)) {
      consider('pose');
    }
    if (EXPRESSION.has(token)) {
      consider('expression');
    }
    if (COMPOSITION.has(token)) {
      consider('composition');
    }
  }

  return best;
}

// WORKAROUND: NSFW membership is DB-verified in the classifier module (exact tags/tokens plus exclusions, so
// "cock_robin"/"year_of_the_cock" do not match). A few standalone explicit markers the classifier omits because
// the word also appears as a substring of a benign tag are re-checked here as a tail guard (porn, nsfw, etc.).
function isExplicitTag(tag) {
  if (classifier.isCategory(String(tag), 'nsfw')) {
    return true;
  }
  return /\b(porn|pornographic|nsfw)\b/.test(String(tag).toLowerCase());
}

// WORKAROUND: one ordering profile does not fit every prompt — the study distinguishes explicit
// (subject-first), scenic/character-less (scene-first), and the default character SFW prompt. The mode
// is recognized from the tags themselves so callers don't have to know which profile applies.
function recognizeMode(tags) {
  const list = tags || [];
  if (list.some(isExplicitTag)) {
    return 'nsfw';
  }
  const classes = list.map(classifyTag);
  if (!classes.includes('count') && !classes.includes('character')) {
    return 'scenic';
  }
  return 'default';
}

const MODE_WEIGHT = {
  default: CATEGORY_WEIGHT,
  nsfw: NSFW_CATEGORY_WEIGHT,
  scenic: SCENIC_CATEGORY_WEIGHT
};

function orderTags(tags, options = {}) {
  const list = tags || [];
  const mode = options.mode || recognizeMode(list);
  const weights = MODE_WEIGHT[mode] || CATEGORY_WEIGHT;
  return list
    .map((tag) => ({ tag, weight: weights[classifyTag(tag)] }))
    .sort((a, b) => a.weight - b.weight)
    .map((entry) => entry.tag);
}

